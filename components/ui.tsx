import * as React from "react"
import { cn } from "@/lib/utils"

export interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: 'default' | 'outline' | 'ghost' | 'destructive';
  size?: 'default' | 'sm' | 'lg' | 'icon';
}
export const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant = 'default', size = 'default', ...props }, ref) => {
    return (
      <button
        ref={ref}
        className={cn(
          "inline-flex items-center justify-center rounded-md text-sm font-medium transition-colors focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-slate-950 disabled:pointer-events-none disabled:opacity-50",
          size === 'default' && "h-9 px-4 py-2",
          size === 'sm' && "h-8 rounded-md px-3 text-xs",
          size === 'lg' && "h-10 rounded-md px-8",
          size === 'icon' && "h-9 w-9",
          variant === 'default' && "bg-blue-600 text-white hover:bg-blue-700 shadow-sm",
          variant === 'outline' && "border border-slate-200 bg-white hover:bg-slate-100 text-slate-900",
          variant === 'ghost' && "hover:bg-slate-100 hover:text-slate-900",
          variant === 'destructive' && "bg-red-500 text-white hover:bg-red-600 shadow-sm",
          className
        )}
        {...props}
      />
    )
  }
)
Button.displayName = "Button"

